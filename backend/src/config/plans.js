export const PLAN_ORDER = ['nano', 'lite', 'pro', 'max', 'enterprise'];

export function normalizePlanId(planId = 'nano') {
  if (!planId || typeof planId !== 'string') return 'nano';
  const lowered = planId.trim().toLowerCase();
  const mapped = PLAN_ALIASES[lowered] || lowered;
  return PLANS[mapped] ? mapped : 'nano';
}

export function getPlanConfig(planId = 'nano') {
  return PLANS[normalizePlanId(planId)] || PLANS.nano;
}

/**
 * Returns flat legacy limit keys plus canonical nested limits/features/access
 * so existing callers and new entitlement checks read from the exact same data.
 */
export function getPlanLimits(planId = 'nano') {
  const cfg = getPlanConfig(planId);
  return {
    plan_id: cfg.plan_id,
    name: cfg.name,
    monthlyViews: cfg.limits.monthly_events,
    storageLimit: cfg.limits.storage_limit_bytes,
    projectLimit: cfg.limits.projects,
    allowedOriginsLimit: cfg.limits.origins_per_project,
    teamMembersLimit: cfg.limits.team_members,
    retentionDays: cfg.limits.retention_days,
    refreshRate: cfg.limits.dashboard_refresh_seconds,
    apiRequestsPerMinute: cfg.limits.api_requests_per_minute,
    ingestionEventsPerSecond: cfg.limits.ingestion_events_per_second,
    ingestionBurst: cfg.limits.ingestion_burst,
    share_report: cfg.limits.shared_reports_per_month,
    shareLinkExpiryDays: cfg.limits.share_link_expiry_days,
    liveLogs: cfg.features.live_visitor_logs,
    emailIntegrity: cfg.features.email_integrity,
    amount: cfg.price,
    price_inr: cfg.price_inr,
    price_usd: cfg.price_usd,
    limits: { ...cfg.limits },
    features: { ...cfg.features },
    access: { ...cfg.access },
  };
}

export function hasFeature(planId, featureKey) {
  const cfg = getPlanConfig(planId);
  return Boolean(cfg.features[featureKey]);
}

export function hasSurfaceAccess(planId, surfaceKey) {
  const cfg = getPlanConfig(planId);
  return Boolean(cfg.access[surfaceKey]);
}

export function listPublicPlans() {
  return PLAN_ORDER.map((id) => {
    const cfg = PLANS[id];
    const isEnterprise = id === 'enterprise';
    return {
      id: cfg.id,
      plan_id: cfg.plan_id,
      name: cfg.name,
      price: cfg.price,
      price_usd: isEnterprise ? 'custom' : cfg.price_usd,
      price_inr: isEnterprise ? 'custom' : cfg.price_inr,
      currency: cfg.currency,
      interval: cfg.interval,
      billing_interval: cfg.billing_interval,
      description: cfg.description,
      features: [...cfg.displayFeatures],
      entitlements: { ...cfg.features },
      access: { ...cfg.access },
      buttonText: cfg.buttonText,
      ...(cfg.popular ? { popular: true } : {}),
      limits: {
        monthlyViews: isEnterprise ? 'custom' : cfg.limits.monthly_events,
        projectLimit: isEnterprise ? 'custom' : cfg.limits.projects,
        allowedOriginsLimit: isEnterprise ? 'custom' : cfg.limits.origins_per_project,
        teamMembersLimit: isEnterprise ? 'custom' : cfg.limits.team_members,
        retentionDays: isEnterprise ? 'custom' : cfg.limits.retention_days,
        refreshRate: cfg.limits.dashboard_refresh_seconds,
        apiRequestsPerMinute: isEnterprise ? 'custom' : cfg.limits.api_requests_per_minute,
        ingestionEventsPerSecond: isEnterprise ? 'custom' : cfg.limits.ingestion_events_per_second,
        ingestionBurst: isEnterprise ? 'custom' : cfg.limits.ingestion_burst,
        sharedReportsPerMonth: isEnterprise ? 'custom' : cfg.limits.shared_reports_per_month,
        shareLinkExpiryDays: isEnterprise ? 'custom' : cfg.limits.share_link_expiry_days,
      },
    };
  });
}

